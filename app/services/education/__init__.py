"""Short, deterministic lessons for checking medical information independently."""

from dataclasses import dataclass


@dataclass(frozen=True)
class Lesson:
    title: str
    body: str


LESSONS = (
    Lesson(
        "1/5 · Сформулируйте утверждение",
        "Отделите проверяемый факт от эмоций, мнения и личного опыта. "
        "Сохраните важные условия: кто, что, когда и для кого утверждается.",
    ),
    Lesson(
        "2/5 · Найдите первоисточник",
        "Проверьте автора, дату и ссылку на исходное исследование или рекомендацию. "
        "Пересказ в соцсетях не заменяет полный первоисточник.",
    ),
    Lesson(
        "3/5 · Оцените качество доказательств",
        "Приоритет обычно у клинических рекомендаций, государственных медицинских "
        "организаций и систематических обзоров. Один отзыв или рекламная статья слабее.",
    ),
    Lesson(
        "4/5 · Проверьте контекст",
        "Смотрите на размер и характеристики группы, дозировку, длительность наблюдения "
        "и ограничения. Результат для одной группы нельзя автоматически переносить на всех.",
    ),
    Lesson(
        "5/5 · Не путайте связь и причину",
        "Если два явления встречаются вместе, это ещё не доказывает, что одно вызвало другое. "
        "Для решений о лечении и симптомах обращайтесь к квалифицированному специалисту.",
    ),
)


def lesson_page(page: int) -> str:
    lesson = LESSONS[min(max(page, 0), len(LESSONS) - 1)]
    return f"📚 Как проверять медицинскую информацию\n\n{lesson.title}\n\n{lesson.body}"
