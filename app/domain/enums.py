    MEDICAL_CLAIM = "MEDICAL_CLAIM"
    ADVICE = "ADVICE"
    OPINION = "OPINION"
    EXPERIENCE = "EXPERIENCE"
    NOT_CHECKABLE = "NOT_CHECKABLE"


